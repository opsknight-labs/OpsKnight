-- Squire knowledge memory and proactive notes. Additive only: one enum and four new, empty tables (their
-- indexes are created here, on empty tables, so nothing is locked for long). No existing row is rewritten.
SET lock_timeout = '2s';
SET statement_timeout = '10s';

CREATE TYPE "KnowledgeSourceKind" AS ENUM ('POSTMORTEM', 'RUNBOOK_STEP', 'RESOLUTION_NOTE', 'INCIDENT_NOTE', 'SERVICE_FACT');

CREATE TABLE "KnowledgeChunk" (
  "id" TEXT NOT NULL,
  "sourceKind" "KnowledgeSourceKind" NOT NULL,
  "sourceId" TEXT NOT NULL,
  "chunkIndex" INTEGER NOT NULL DEFAULT 0,
  "serviceId" TEXT,
  "teamId" TEXT,
  "incidentId" TEXT,
  "postmortemId" TEXT,
  "incidentNoteId" TEXT,
  "runbookId" TEXT,
  "title" TEXT NOT NULL,
  "text" TEXT NOT NULL,
  "contentHash" TEXT NOT NULL,
  -- Stored, generated by the database, like IncidentFingerprint.searchVector; the application never writes it.
  "searchVector" tsvector GENERATED ALWAYS AS (to_tsvector('simple', "title" || ' ' || "text")) STORED,
  "embedding" REAL[],
  "embeddingModel" TEXT,
  "approvedById" TEXT,
  "sourceCreatedAt" TIMESTAMP(3) NOT NULL,
  "sourceUpdatedAt" TIMESTAMP(3) NOT NULL,
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updatedAt" TIMESTAMP(3) NOT NULL,
  CONSTRAINT "KnowledgeChunk_pkey" PRIMARY KEY ("id")
);
CREATE UNIQUE INDEX "uq_knowledge_chunk_source" ON "KnowledgeChunk"("sourceKind", "sourceId", "chunkIndex");
CREATE INDEX "idx_knowledge_chunk_service" ON "KnowledgeChunk"("serviceId", "sourceKind");
CREATE INDEX "idx_knowledge_chunk_team" ON "KnowledgeChunk"("teamId");
CREATE INDEX "idx_knowledge_chunk_retention" ON "KnowledgeChunk"("sourceCreatedAt");
CREATE INDEX "idx_knowledge_chunk_embedding_model" ON "KnowledgeChunk"("embeddingModel");
CREATE INDEX "idx_knowledge_chunk_incident" ON "KnowledgeChunk"("incidentId");
CREATE INDEX "idx_knowledge_chunk_postmortem" ON "KnowledgeChunk"("postmortemId");
CREATE INDEX "idx_knowledge_chunk_note" ON "KnowledgeChunk"("incidentNoteId");
CREATE INDEX "idx_knowledge_chunk_runbook" ON "KnowledgeChunk"("runbookId");
CREATE INDEX "idx_knowledge_chunk_search" ON "KnowledgeChunk" USING GIN ("searchVector");

ALTER TABLE "KnowledgeChunk" ADD CONSTRAINT "KnowledgeChunk_serviceId_fkey"
  FOREIGN KEY ("serviceId") REFERENCES "Service"("id") ON DELETE CASCADE ON UPDATE CASCADE;
ALTER TABLE "KnowledgeChunk" ADD CONSTRAINT "KnowledgeChunk_incidentId_fkey"
  FOREIGN KEY ("incidentId") REFERENCES "Incident"("id") ON DELETE CASCADE ON UPDATE CASCADE;
ALTER TABLE "KnowledgeChunk" ADD CONSTRAINT "KnowledgeChunk_postmortemId_fkey"
  FOREIGN KEY ("postmortemId") REFERENCES "Postmortem"("id") ON DELETE CASCADE ON UPDATE CASCADE;
ALTER TABLE "KnowledgeChunk" ADD CONSTRAINT "KnowledgeChunk_incidentNoteId_fkey"
  FOREIGN KEY ("incidentNoteId") REFERENCES "IncidentNote"("id") ON DELETE CASCADE ON UPDATE CASCADE;
ALTER TABLE "KnowledgeChunk" ADD CONSTRAINT "KnowledgeChunk_runbookId_fkey"
  FOREIGN KEY ("runbookId") REFERENCES "Runbook"("id") ON DELETE CASCADE ON UPDATE CASCADE;
ALTER TABLE "KnowledgeChunk" ADD CONSTRAINT "KnowledgeChunk_approvedById_fkey"
  FOREIGN KEY ("approvedById") REFERENCES "User"("id") ON DELETE SET NULL ON UPDATE CASCADE;

-- Trigram search is optional: installs without pg_trgm keep full-text search only.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'pg_trgm') THEN
    EXECUTE 'CREATE INDEX IF NOT EXISTS "idx_knowledge_chunk_trgm" ON "KnowledgeChunk" USING GIN ("text" gin_trgm_ops)';
  END IF;
END
$$;

CREATE TABLE "SquireMemorySettings" (
  "id" TEXT NOT NULL DEFAULT 'default',
  "knowledgeEnabled" BOOLEAN NOT NULL DEFAULT false,
  "revision" INTEGER NOT NULL DEFAULT 0,
  "updatedAt" TIMESTAMP(3) NOT NULL,
  CONSTRAINT "SquireMemorySettings_pkey" PRIMARY KEY ("id")
);

CREATE TABLE "SquireServicePolicy" (
  "serviceId" TEXT NOT NULL,
  "briefingEnabled" BOOLEAN NOT NULL DEFAULT false,
  "nudgeAfterMinutes" INTEGER,
  "postmortemDraftEnabled" BOOLEAN NOT NULL DEFAULT false,
  "revision" INTEGER NOT NULL DEFAULT 0,
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updatedAt" TIMESTAMP(3) NOT NULL,
  CONSTRAINT "SquireServicePolicy_pkey" PRIMARY KEY ("serviceId")
);
ALTER TABLE "SquireServicePolicy" ADD CONSTRAINT "SquireServicePolicy_serviceId_fkey"
  FOREIGN KEY ("serviceId") REFERENCES "Service"("id") ON DELETE CASCADE ON UPDATE CASCADE;

CREATE TABLE "SquireProactiveNote" (
  "id" TEXT NOT NULL,
  "incidentId" TEXT NOT NULL,
  "kind" TEXT NOT NULL,
  "mode" TEXT NOT NULL,
  "content" JSONB NOT NULL,
  "model" TEXT,
  "generation" INTEGER NOT NULL,
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updatedAt" TIMESTAMP(3) NOT NULL,
  CONSTRAINT "SquireProactiveNote_pkey" PRIMARY KEY ("id")
);
CREATE UNIQUE INDEX "uq_squire_proactive_note" ON "SquireProactiveNote"("incidentId", "kind");
CREATE INDEX "idx_squire_proactive_note_retention" ON "SquireProactiveNote"("createdAt");
ALTER TABLE "SquireProactiveNote" ADD CONSTRAINT "SquireProactiveNote_incidentId_fkey"
  FOREIGN KEY ("incidentId") REFERENCES "Incident"("id") ON DELETE CASCADE ON UPDATE CASCADE;

RESET statement_timeout;
RESET lock_timeout;
